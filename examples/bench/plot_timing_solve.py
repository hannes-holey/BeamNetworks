"""Plot solve timing and peak memory vs. network size for all solvers.

Two panels side by side: left = wall time, right = peak memory (MiB).
Both axes share the x-axis (DOF count) on a log scale.

Expected input files (generated by run_bench_solve.py):
    time_solve_{direct,cg,ilu,ssor}.txt
    time_solve_cholesky.txt              [optional, requires scikit-sparse]
    time_solve_{amg,amg_rs}.txt          [optional, requires pyamg]

Each file has three columns: [num_dof, time_s, peak_mem_MiB].

Run with::

    cd examples/bench
    python plot_timing_solve.py
"""

import os
import numpy as np
import matplotlib.pyplot as plt


BENCH_PATH = os.path.dirname(os.path.abspath(__file__))

SOLVERS_DIRECT = ['direct', 'cholesky']
SOLVERS_ITERATIVE = ['cg', 'ilu', 'ssor', 'amg', 'amg_rs']

COLORS = {'direct': 'C0', 'cholesky': 'C4',
          'cg': 'C1', 'ilu': 'C2', 'ssor': 'C3', 'amg': 'C5', 'amg_rs': 'C6'}
MARKERS = {'direct': 'X', 'cholesky': '*',
           'cg': 'o', 'ilu': 'D', 'ssor': 's', 'amg': '^', 'amg_rs': 'v'}


def load(fname):
    path = os.path.join(BENCH_PATH, fname)
    if not os.path.exists(path):
        return None, None, None
    data = np.loadtxt(path)
    n, t, m = data[:, 0], data[:, 1], data[:, 2]
    mask = np.isfinite(t) & np.isfinite(m)
    return n[mask], t[mask], m[mask]


if __name__ == '__main__':

    style = os.path.join(BENCH_PATH, '..', 'beams.mplstyle')
    if os.path.exists(style):
        plt.style.use(style)

    fig, axes = plt.subplots(1, 2, figsize=(10, 5), sharex=True)
    ax_t, ax_m = axes

    all_n = []

    for solver in SOLVERS_DIRECT + SOLVERS_ITERATIVE:
        n, t, m = load(f'time_solve_{solver}.txt')
        if n is None:
            continue
        fmt = f'-{MARKERS[solver]}'
        color = COLORS[solver]
        ax_t.loglog(n, t, fmt, color=color, label=solver)
        ax_m.loglog(n, m, fmt, color=color, label=solver)
        all_n.append(n)

    if all_n:
        n_ref = np.concatenate(all_n)
        n_line = np.array([n_ref.min(), n_ref.max()])
        ax_t.loglog(n_line, 1e-6 * n_line, ':', color='0.7', lw=0.8, zorder=0,
                    label=r'$\mathcal{O}(N)$')

    ax_t.set_xlabel('DOF')
    ax_t.set_ylabel('Solve time (s)')
    ax_t.legend(fontsize=8, ncol=2)

    ax_m.set_xlabel('DOF')
    ax_m.set_ylabel('Peak memory (MiB)')
    ax_m.legend(fontsize=8, ncol=2)

    plt.show()
